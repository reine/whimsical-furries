# Builds hooks/forest.ts from the art files: the forest, with the wizard cat
# pinned bottom-right and the mage cat pinned bottom-left.
# Run: python3 art/compose.py
#
# The forest is drawn 1600x900 and scaled to cover the window, so a window
# narrower than 16:9 crops its sides and a wider one crops top and bottom.
# The media rules below move (and on small windows shrink) the cats so they
# stay inside the visible part of the scene.
import json, os, re
here = os.path.dirname(os.path.abspath(__file__))
def inner(name):
    s = open(os.path.join(here, name)).read()
    return re.sub(r'^\s*<svg[^>]*>', '', s).rsplit('</svg>', 1)[0]

MARGIN = 15  # scene units between a cat and the visible edge

# (media query or None, narrowest aspect in that range, top y, size)
SPOTS = [
    (None, 16 / 9, 435, 1),
    ('(min-aspect-ratio: 2/1)', 16 / 9, 343, 1),
    ('(max-aspect-ratio: 16/9)', 1.6, 470, 1),
    ('(max-aspect-ratio: 8/5)', 1.5, 470, 1),
    ('(max-aspect-ratio: 3/2)', 1.25, 510, 0.9),
    ('(max-aspect-ratio: 5/4)', 1.0, 550, 0.8),
    ('(max-aspect-ratio: 1/1)', 0.8, 610, 0.65),
    ('(max-aspect-ratio: 4/5)', 0.6, 610, 0.65),
]

# (file, class, side, size, how far its drawing reaches toward that edge)
CATS = [
    ('cat-mage.svg', 'magespot', 'left', 0.94, 12),
    ('cat-wizard.svg', 'wizardspot', 'right', 1, 288),
]

def spot(aspect, y, s, side, k, reach):
    visible_right = 1600 if aspect >= 16 / 9 else 800 + 450 * aspect
    size = s * k
    if side == 'right':
        x = visible_right - MARGIN - reach * size
    else:
        x = (1600 - visible_right) + MARGIN - reach * size
    return round(x), round(y + 400 * (s - size)), round(size, 3)

css = []
for q, aspect, y, s in SPOTS:
    rules = ''
    for _, c, side, k, reach in CATS:
        x, yy, size = spot(aspect, y, s, side, k, reach)
        rules += f'.{c}{{transform:translate({x}px,{yy}px) scale({size})}}'
    css.append(rules if q is None else f'@media {q}{{{rules}}}')

forest = open(os.path.join(here, 'forest.svg')).read().rsplit('</svg>', 1)[0]
cats = f'<style>{"".join(css)}</style>'
for f, c, side, k, reach in CATS:
    x, y, size = spot(*SPOTS[0][1:], side, k, reach)
    cats += (f'<g class="{c}" transform="translate({x} {y}) scale({size})">'
             f'<svg width="300" height="400" viewBox="0 0 300 400">{inner(f)}</svg></g>')
scene = forest + cats + '</svg>'
assert len(scene) < 131072, len(scene)
open(os.path.join(here, 'scene.svg'), 'w').write(scene)
open(os.path.join(here, '..', 'hooks', 'forest.ts'), 'w').write(
    '// Generated by art/compose.py from the art files. Edit those, then rerun it.\nexport const FOREST = ' + json.dumps(scene) + '\n')
print(len(scene), 'chars')
